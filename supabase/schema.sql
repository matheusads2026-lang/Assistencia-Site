-- Execute no SQL Editor do Supabase.
create table if not exists public.produtos (
 id bigint generated by default as identity primary key,
 nome text not null, categoria text not null, marca text, descricao text,
 preco numeric(12,2) not null default 0 check(preco >= 0), imagem text,
 created_at timestamptz not null default now()
);
create table if not exists public.servicos (
 id bigint generated by default as identity primary key,
 nome text not null, categoria text not null, marca text, descricao text,
 preco numeric(12,2) not null default 0 check(preco >= 0), imagem text,
 created_at timestamptz not null default now()
);
alter table public.produtos enable row level security;
alter table public.servicos enable row level security;
-- Leitura pública (catálogo).
create policy "public read produtos" on public.produtos for select to anon, authenticated using (true);
create policy "public read servicos" on public.servicos for select to anon, authenticated using (true);
-- Políticas de escrita restritas ao ID do dono. Substitua UUID_DO_DONO pelo UUID real do Auth.
create policy "owner insert produtos" on public.produtos for insert to authenticated with check (auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner update produtos" on public.produtos for update to authenticated using (auth.uid() = 'UUID_DO_DONO'::uuid) with check (auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner delete produtos" on public.produtos for delete to authenticated using (auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner insert servicos" on public.servicos for insert to authenticated with check (auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner update servicos" on public.servicos for update to authenticated using (auth.uid() = 'UUID_DO_DONO'::uuid) with check (auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner delete servicos" on public.servicos for delete to authenticated using (auth.uid() = 'UUID_DO_DONO'::uuid);
-- Storage: crie bucket catalogo PUBLIC (public URLs para imagem); policies restringem upload/deleção ao dono.
insert into storage.buckets (id,name,public) values ('catalogo','catalogo',true) on conflict (id) do update set public=true;
create policy "public catalog image read" on storage.objects for select to anon, authenticated using (bucket_id='catalogo');
create policy "owner catalog upload" on storage.objects for insert to authenticated with check (bucket_id='catalogo' and auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner catalog update" on storage.objects for update to authenticated using (bucket_id='catalogo' and auth.uid() = 'UUID_DO_DONO'::uuid) with check (bucket_id='catalogo' and auth.uid() = 'UUID_DO_DONO'::uuid);
create policy "owner catalog delete" on storage.objects for delete to authenticated using (bucket_id='catalogo' and auth.uid() = 'UUID_DO_DONO'::uuid);
